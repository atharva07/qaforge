class TestRunPermission(BasePermission):
    """
    Object-level permissions for TestRun.

    Rules:
    - Authenticated users can view test runs.
    - ADMIN can create and modify any test run.
    - QA_ENGINEER can create test runs and modify their own.
    - DEVELOPER can create test runs.
    - DEVELOPER cannot modify an existing test run.
    - VIEWER cannot create or modify test runs.
    """
    def has_permission(self, request, view):
        if not request.user.is_authenticated:
            return False

        # Anyone Authenticated can read
        if request.method in SAFE_METHODS:
            return True

        # ADMIN, QA_ENGINEER and DEVELOPER
        # can create TestRuns
        return request.user.role in [
            User.Role.ADMIN,
            User.Role.QA_ENGINEER,
            User.Role.DEVELOPER,
        ]
    
    def has_object_permission(self, request, view, obj):
        # Everyone authenticated can view
        if request.method in SAFE_METHODS:
            return True

        # Admin
        if request.user.role == User.Role.ADMIN:
            return True

        # QA can modify their own TestRuns
        if (
            request.user.role == User.Role.QA_ENGINEER
            and obj.created_by == request.user
        ):
            return True

        # Developer can modify their own TestRuns
        if (
            request.user.role == User.Role.DEVELOPER
            and obj.created_by == request.user
        ):
            return True

        # DEVELOPER can create Testruns,
        # but cannot modift existing Testruns.
        return False

class TestResultPermission(BasePermission):
    """
    TestResults are read-only through the API.

    TestResults should normally be generated by the
    test execution system rather than manually modified
    through the API.
    """

    def has_permission(self, request, view):
        if not request.user.is_authenticated:
            return False

        # Everyone authenticated can view results
        if request.method in SAFE_METHODS:
            return True

        # No direct POST/PUT/PATCH/DELETE through this API
        return False

