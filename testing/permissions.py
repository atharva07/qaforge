from rest_framework.permissions import BasePermission, SAFE_METHODS
from users.models import User
from users.permissions import HasRole

class TestSuiteObjectPermission(BasePermission):
    """
    Object level permissions TestSuite.

    Rules:
    - Authenticated users can view suites
    - ADMIN can create an modify suite
    - QA ENGINEER can create suites and modify suites they created
    - DEVELOPER cannot create or modify suites
    - VIEWER cannot create or modify suites
    """
    def has_permission(self, request, view):
        if not request.user.is_authenticated:
            return False

        # Everyone authenticated can read
        if request.method in SAFE_METHODS:
            return True

        # Only ADMIN and QA_ENGINEER can create/modify suites
        return request.user.role in [
            User.Role.ADMIN,
            User.Role.QA_ENGINEER,
        ]
    
    def has_object_permission(self, request, view, obj):
        # Anyone Authenticated can view
        if request.method in SAFE_METHODS:
            return True

        # Anyone can modify any suite
        if request.user.role == User.role.ADMIN:
            return True

        # QA Engineer can modify suites they created
        return (
            request.user.role == User.Role.QA_ENGINEER
            and obj.created_by == request.user
        )

